//! Generates `keys.rs` (one constant per English message ID) and the embedded resource table
//! from `locales/<lang>/*.ftl`, so a typo in a key is a compile error (ADR-0021).

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn main() -> Result<(), Box<dyn Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("locales");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut resources = String::from(
        "/// Embedded `(locale, file, source)` triples.\npub(crate) const RESOURCES: &[(&str, &str, &str)] = &[\n",
    );
    let mut langs: Vec<_> = fs::read_dir(&root)?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    langs.sort();
    let mut en_ids: Vec<String> = Vec::new();
    for lang_dir in &langs {
        let lang = lang_dir
            .file_name()
            .and_then(|s| s.to_str())
            .ok_or("bad locale dir")?
            .to_owned();
        let mut files: Vec<_> = fs::read_dir(lang_dir)?
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "ftl"))
            .collect();
        files.sort();
        for file in files {
            println!("cargo:rerun-if-changed={}", file.display());
            let name = file
                .file_name()
                .and_then(|s| s.to_str())
                .ok_or("bad file name")?
                .to_owned();
            writeln!(
                resources,
                "    ({lang:?}, {name:?}, include_str!({:?})),",
                file.display().to_string()
            )?;
            if lang == "en" {
                for line in fs::read_to_string(&file)?.lines() {
                    if let Some(id) = message_id(line) {
                        en_ids.push(id.to_owned());
                    }
                }
            }
        }
    }
    resources.push_str("];\n");
    en_ids.sort();
    en_ids.dedup();

    let mut keys = String::from("// Generated by build.rs from locales/en/*.ftl — do not edit.\n");
    for id in &en_ids {
        let const_name: String = id
            .chars()
            .map(|c| {
                if c == '-' {
                    '_'
                } else {
                    c.to_ascii_uppercase()
                }
            })
            .collect();
        writeln!(
            keys,
            "/// Message `{id}`.\npub const {const_name}: crate::Key = crate::Key({id:?});"
        )?;
    }
    keys.push_str("/// Every key defined in English.\npub const ALL: &[crate::Key] = &[\n");
    for id in &en_ids {
        writeln!(keys, "    crate::Key({id:?}),")?;
    }
    keys.push_str("];\n");

    let out = Path::new(&std::env::var("OUT_DIR")?).to_path_buf();
    fs::write(out.join("keys.rs"), keys)?;
    fs::write(out.join("resources.rs"), resources)?;
    Ok(())
}

/// A top-level Fluent message ID at the start of `line` (`id = ...`), ignoring terms and comments.
fn message_id(line: &str) -> Option<&str> {
    let first = line.chars().next()?;
    if !first.is_ascii_alphabetic() {
        return None;
    }
    let (id, _value) = line.split_once('=')?;
    let id = id.trim();
    let valid = id
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    valid.then_some(id)
}
